#!/bin/sh
# Runs the service the way the systemd unit does on a NetworkManager machine
# without systemd-resolved: /etc/resolv.conf is a link into /run, the whole
# file system read-only (ProtectSystem=strict) except /etc, /proc/sys/net and
# the runtime directory; a private /tmp; and only the capabilities the unit's
# CapabilityBoundingSet leaves (UNIT_CAPS, e.g. "+net_admin,+chown").
# Run under `unshare -m`, so none of these mounts reach the real machine.
# $1 = a directory standing for this machine's /etc; rest = the command.
# /run/NetworkManager must exist; it gets a fresh resolv.conf each start, as
# after a reboot.
set -e
ETC="$1"; shift
mount --make-rprivate /
mount -t tmpfs tmpfs /run/NetworkManager
printf '# Generated by NetworkManager\nnameserver 10.200.0.1\n' > /run/NetworkManager/resolv.conf
mount --bind "$ETC" /etc
mount --bind /run/hidravpn /run/hidravpn
mount -t tmpfs tmpfs /tmp
mount -o remount,bind,ro /
mount -o remount,bind,ro /run/NetworkManager
# ETC_RO=1: /etc read-only too, so the DNS step of a connection fails.
[ "${ETC_RO:-0}" = 1 ] && mount -o remount,bind,ro /etc
exec setpriv --bounding-set=-all,"$UNIT_CAPS" --inh-caps=-all "$@"
